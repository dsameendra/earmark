import AppCore
import Foundation

/// SRT, WebVTT, ASS/SSA, SBV, TTML/DFXP and LRC.
///
/// Cues honour ``SubtitleConstraints`` (line length, lines per cue, min/max duration, min gap, punctuation splitting) and never
/// overlap. Speakers appear as `<v Name>` (VTT), the Name field and per-speaker styles (ASS), `ttm:agent` (TTML) or a `Name:`
/// prefix on the first cue of a turn (SRT, SBV, LRC). TTML carries `xml:lang` per cue (EXP-AC-10).
public struct SubtitleExporter: Exporter {
    public init() {}
    public var formats: Set<ExportFormat> { [.srt, .vtt, .ass, .sbv, .ttml, .lrc] }

    public func export(_ document: TranscriptDocument, options: ExportOptions) async throws -> ExportArtifact {
        try ExportPipeline.validate(options, supported: formats)
        let entries = ExportPipeline.entries(document, options: options)
        let text: String
        if options.format == .lrc {
            text = lrc(document, entries, options)
        } else {
            let cues = CueBuilder.build(entries, constraints: options.subtitle, bilingual: options.translation == .bilingual)
            switch options.format {
            case .srt: text = srt(cues, options)
            case .vtt: text = vtt(cues, options)
            case .sbv: text = sbv(cues, options)
            case .ass: text = ass(document, cues, options)
            default: text = ttml(document, entries, cues, options)
            }
        }
        return makeArtifact(document, options: options, data: Data(text.utf8))
    }

    /// Cue text lines with an optional `Name: ` prefix on the first line of a turn.
    private func plainLines(_ cue: Cue, _ options: ExportOptions) -> [String] {
        var lines = cue.lines
        if options.includeSpeakers, cue.isTurnStart, let name = cue.speaker?.name, !lines.isEmpty { lines[0] = "\(name): \(lines[0])" }
        return lines + cue.translationLines
    }

    private func srt(_ cues: [Cue], _ options: ExportOptions) -> String {
        var out = ""
        for (index, cue) in cues.enumerated() {
            out += "\(index + 1)\n\(Format.srt(cue.startMS)) --> \(Format.srt(cue.endMS))\n"
            out += plainLines(cue, options).joined(separator: "\n") + "\n\n"
        }
        return out
    }

    private func sbv(_ cues: [Cue], _ options: ExportOptions) -> String {
        var out = ""
        for cue in cues {
            out += "\(Format.sbv(cue.startMS)),\(Format.sbv(cue.endMS))\n" + plainLines(cue, options).joined(separator: "\n") + "\n\n"
        }
        return out
    }

    private func vttEscape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
    }

    private func vtt(_ cues: [Cue], _ options: ExportOptions) -> String {
        var out = "WEBVTT\n\n"
        for (index, cue) in cues.enumerated() {
            out += "\(index + 1)\n\(Format.vtt(cue.startMS)) --> \(Format.vtt(cue.endMS))\n"
            let body = (cue.lines + cue.translationLines).map(vttEscape).joined(separator: "\n")
            if options.includeSpeakers, let name = cue.speaker?.name {
                out += "<v \(vttEscape(name).replacingOccurrences(of: "\n", with: " "))>\(body)</v>\n\n"
            } else {
                out += body + "\n\n"
            }
        }
        return out
    }

    // MARK: ASS

    private static let sinhalaFont = "Sinhala Sangam MN"

    /// `#RRGGBB` to ASS `&H00BBGGRR`.
    static func assColor(_ hex: String) -> String {
        let digits = hex.trimmingCharacters(in: CharacterSet(charactersIn: "#"))
        guard digits.count == 6, UInt32(digits, radix: 16) != nil else { return "&H00FFFFFF" }
        let r = digits.prefix(2), g = digits.dropFirst(2).prefix(2), b = digits.suffix(2)
        return "&H00\(b)\(g)\(r)".uppercased()
    }

    private func assName(_ name: String) -> String {
        name.replacingOccurrences(of: ",", with: " ").replacingOccurrences(of: "\n", with: " ")
    }

    private func assText(_ text: String) -> String {
        text.replacingOccurrences(of: "{", with: "(").replacingOccurrences(of: "}", with: ")").replacingOccurrences(of: "\n", with: "\\N")
    }

    private func ass(_ document: TranscriptDocument, _ cues: [Cue], _ options: ExportOptions) -> String {
        let font = options.fontFamily ?? "Helvetica Neue"
        var out = """
            [Script Info]
            ; Generated by Earmark
            Title: \(assName(document.transcript.title))
            ScriptType: v4.00+
            WrapStyle: 0
            ScaledBorderAndShadow: yes
            PlayResX: 1920
            PlayResY: 1080

            [V4+ Styles]
            Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, \
            ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding

            """
        func style(_ name: String, _ color: String) -> String {
            "Style: \(name),\(font),56,\(color),&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2,1,2,60,60,50,1\n"
        }
        out += style("Default", "&H00FFFFFF")
        var styled: [String] = []
        if options.includeSpeakers {
            for speaker in document.transcript.speakers where cues.contains(where: { $0.speaker?.id == speaker.id }) {
                let name = assName(speaker.name)
                guard !styled.contains(name), name != "Default" else { continue }
                styled.append(name)
                out += style(name, Self.assColor(speaker.colorHex))
            }
        }
        out += "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        for cue in cues {
            var styleName = "Default"
            var nameField = ""
            if options.includeSpeakers, let speaker = cue.speaker {
                nameField = assName(speaker.name)
                if styled.contains(nameField) { styleName = nameField }
            }
            var lines = cue.lines.map(assText)
            if cue.language?.primary == .sinhala { lines = lines.map { "{\\fn\(Self.sinhalaFont)}" + $0 } }
            var secondary = cue.translationLines.map(assText)
            if cue.translationLanguage?.primary == .sinhala { secondary = secondary.map { "{\\fn\(Self.sinhalaFont)}" + $0 } }
            let text = (lines + secondary).joined(separator: "\\N")
            out += "Dialogue: 0,\(Format.ass(cue.startMS)),\(Format.ass(cue.endMS)),\(styleName),\(nameField),0,0,0,,\(text)\n"
        }
        return out
    }

    // MARK: TTML

    private func ttml(_ document: TranscriptDocument, _ entries: [Entry], _ cues: [Cue], _ options: ExportOptions) -> String {
        let root = ExportPipeline.primaryLanguage(document, entries: entries)
        var agents: [SpeakerID: String] = [:]
        var agentOrder: [Speaker] = []
        if options.includeSpeakers {
            for cue in cues {
                if let speaker = cue.speaker, agents[speaker.id] == nil {
                    agents[speaker.id] = "spk-\(agents.count + 1)"
                    agentOrder.append(speaker)
                }
            }
        }
        var out = """
            <?xml version="1.0" encoding="UTF-8"?>
            <tt xmlns="http://www.w3.org/ns/ttml" xmlns:tts="http://www.w3.org/ns/ttml#styling" xmlns:ttm="http://www.w3.org/ns/ttml#metadata" xml:lang="\(XML.escape(root.rawValue))">
              <head>
                <metadata>
                  <ttm:title>\(XML.escape(document.transcript.title))</ttm:title>

            """
        for speaker in agentOrder {
            out += "      <ttm:agent xml:id=\"\(agents[speaker.id]!)\" type=\"person\"><ttm:name type=\"full\">\(XML.escape(speaker.name))</ttm:name></ttm:agent>\n"
        }
        out += "    </metadata>\n    <styling>\n      <style xml:id=\"default\" tts:textAlign=\"center\"/>\n    </styling>\n  </head>\n  <body>\n    <div>\n"
        for cue in cues {
            var attributes = "begin=\"\(Format.vtt(cue.startMS))\" end=\"\(Format.vtt(cue.endMS))\""
            if let language = cue.language { attributes += " xml:lang=\"\(XML.escape(language.rawValue))\"" }
            if let speaker = cue.speaker, let id = agents[speaker.id] { attributes += " ttm:agent=\"\(id)\"" }
            var body = cue.lines.map(XML.escape).joined(separator: "<br/>")
            if !cue.translationLines.isEmpty {
                let lang = cue.translationLanguage.map { " xml:lang=\"\(XML.escape($0.rawValue))\"" } ?? ""
                body = "<span\(cue.language.map { " xml:lang=\"\(XML.escape($0.rawValue))\"" } ?? "")>\(body)</span><br/><span\(lang)>"
                    + cue.translationLines.map(XML.escape).joined(separator: "<br/>") + "</span>"
            }
            out += "      <p \(attributes)>\(body)</p>\n"
        }
        out += "    </div>\n  </body>\n</tt>\n"
        return out
    }

    // MARK: LRC

    private func lrc(_ document: TranscriptDocument, _ entries: [Entry], _ options: ExportOptions) -> String {
        var out = "[ti:\(document.transcript.title.replacingOccurrences(of: "\n", with: " "))]\n"
        let total = Format.ms(document.transcript.duration) / 1000
        out += "[length:\(total / 60):\(total % 60 < 10 ? "0" : "")\(total % 60)]\n"
        var previous: SpeakerID?
        var first = true
        for entry in entries {
            var text = entry.text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            if options.includeSpeakers, let name = entry.speaker?.name, first || previous != entry.speakerID { text = "\(name): \(text)" }
            first = false
            previous = entry.speakerID
            let stamp = "[\(Format.lrc(Format.ms(entry.start)))]"
            out += stamp + text + "\n"
            if let translation = entry.translation { out += stamp + translation.split(whereSeparator: \.isWhitespace).joined(separator: " ") + "\n" }
        }
        return out
    }
}
